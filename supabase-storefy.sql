create or replace function public.storefy_redeem_code(p_user_id uuid, p_codigo text)
returns table (user_id uuid, nivel int, codigo_socio varchar)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_codigo varchar(32) := nullif(upper(trim(coalesce(p_codigo, ''))), '');
  v_profile public.storefy_profiles%rowtype;
  v_convite public.codigos_convite%rowtype;
begin
  select * into v_profile from public.storefy_profiles where storefy_profiles.user_id = p_user_id for update;
  if not found then raise exception 'Perfil nao encontrado'; end if;
  if v_profile.nivel = 10 then
    return query select v_profile.user_id, v_profile.nivel, v_profile.codigo_socio;
    return;
  end if;
  select * into v_convite from public.codigos_convite
  where codigo = v_codigo and status = 'ativo' and usos < max_usos
    and (expira_em is null or expira_em > now()) for update;
  if not found then raise exception 'Codigo invalido ou expirado'; end if;
  update public.codigos_convite set usos = usos + 1, status = case when usos + 1 >= max_usos then 'expirado' else status end where id = v_convite.id;
  update public.storefy_profiles set nivel = 10, codigo_socio = v_codigo, atualizado_em = now() where storefy_profiles.user_id = p_user_id returning * into v_profile;
  return query select v_profile.user_id, v_profile.nivel, v_profile.codigo_socio;
end;
$$;
revoke all on function public.storefy_redeem_code(uuid, text) from public, anon, authenticated;
grant execute on function public.storefy_redeem_code(uuid, text) to service_role;